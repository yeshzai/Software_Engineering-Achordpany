package com.example.achordpany.ui.signup;

public class UsersCredentials {

    public String username;
    public String email;
    public String avatarUID;

    public UsersCredentials() {

    }

    public UsersCredentials(String username, String email, String avatarUID) {
        this.username = username;
        this.email = email;
        this.avatarUID = avatarUID;
    }

}